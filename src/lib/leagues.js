// 역맵: 정규화 클럽명 → 리그
export const CLUB_TO_LEAGUE = (() => {
  const m = new Map();
  for (const [league, clubs] of Object.entries(LEAGUE_CLUBS)) {
    for (const c of clubs) m.set(normalizeTeam(c), league);
  }
  return m;
})();

export const LEAGUES = Object.keys(LEAGUE_CLUBS);

/**
 * 팀명 → 리그 1차 판별. 미상이면 null.
 */
export function leagueOf(rawName) {
  const name = normalizeTeam(rawName);
  if (!name) return null;
  if (name.endsWith('M')) {
    // 여자대표(우즈벡M 등). 단 클럽명이 M으로 끝나는 예외는 사전 우선.
    if (!CLUB_TO_LEAGUE.has(name)) return '국가대표';
  }
  if (NATIONAL_TEAMS.has(name)) return '국가대표';
  return CLUB_TO_LEAGUE.get(name) ?? null;
}
